"use strict";

/* ==========================================================
   DATA SERVICE
========================================================== */

const DataService = {

    data: {}

};

/* ==========================================================
   LOAD
========================================================== */

DataService.load = function (source = {}) {

    this.data = {

        ...source

    };

    return this.data;

};

/* ==========================================================
   GET
========================================================== */

DataService.get = function (key, defaultValue = null) {

    return Object.prototype.hasOwnProperty.call(

        this.data,

        key

    )

        ? this.data[key]

        : defaultValue;

};

/* ==========================================================
   SET
========================================================== */

DataService.set = function (key, value) {

    this.data[key] = value;

    return value;

};

/* ==========================================================
   HAS
========================================================== */

DataService.has = function (key) {

    return Object.prototype.hasOwnProperty.call(

        this.data,

        key

    );

};

/* ==========================================================
   REMOVE
========================================================== */

DataService.remove = function (key) {

    if (!this.has(key)) {

        return false;

    }

    delete this.data[key];

    return true;

};

/* ==========================================================
   CLEAR
========================================================== */

DataService.clear = function () {

    this.data = {};

};

/* ==========================================================
   GET ALL
========================================================== */

DataService.getAll = function () {

    return {

        ...this.data

    };

};

/* ==========================================================
   COUNT
========================================================== */

DataService.count = function () {

    return Object.keys(

        this.data

    ).length;

};

/* ==========================================================
   EXPORT
========================================================== */

window.DataService = DataService;

